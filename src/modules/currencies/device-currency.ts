/** The table turned round, built once. Both are exported for their test. */
export const CURRENCY_BY_ZONE: ReadonlyMap<string, string> = new Map(
  Object.entries(ZONES_BY_CURRENCY).flatMap(([currency, zones]) =>
    zones.map((zone) => [zone, currency] as const),
  ),
);

/**
 * The zone as this runtime names it, which is not always how the device does.
 *
 * Engines disagree over the zones that were renamed — V8 reports
 * `Asia/Calcutta` where Firefox says `Asia/Kolkata` — and both spellings are
 * in the table for those. This catches the rest: a link such as
 * `America/Montreal`, which every engine resolves to a zone that is listed.
 */
function canonical(zone: string): string | null {
  try {
    return new Intl.DateTimeFormat("en-US", {
      timeZone: zone,
    }).resolvedOptions().timeZone;
  } catch {
    return null;
  }
}

/**
 * The currency paid where `zone` is, or null where the table has no answer —
 * no zone, a zone nobody lives in, or one this runtime does not know.
 *
 * Only ever a currency the app supports, so a guess can always be submitted.
 */
export function currencyOfTimezone(
  zone: string | null | undefined,
): string | null {
  if (!zone) return null;
  const currency =
    CURRENCY_BY_ZONE.get(zone) ??
    CURRENCY_BY_ZONE.get(canonical(zone) ?? "") ??
    null;
  return currency !== null && isSupportedCurrency(currency) ? currency : null;
}
