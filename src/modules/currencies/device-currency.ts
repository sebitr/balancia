/**
 * The currency where a device is, read off its time zone.
 *
 * A brand-new account has said nothing about money yet, and the sheet that
 * creates its first group used to answer for it with the euro. That answer is
 * permanent — a group's currency cannot change once it exists — so a Zurich
 * flat share went into euros because nobody had said otherwise. The device
 * had, though: it was already telling the same sheet that its days end at
 * Zurich time. The zone is where somebody is; this table is what that place
 * pays in.
 *
 * The zone and not the language, deliberately. `en-US` is what a great many
 * phones far from America are set to, so a region read off the language would
 * put a London flat share into dollars as confidently as this one put Zurich
 * into euros. A clock set to Europe/London is a much better witness.
 *
 * Grouped by currency rather than by zone, so a reviewer can read "every zone
 * that pays in francs" in one place. Only currencies the app supports appear,
 * and the test beside this file holds every key to a zone the runtime knows
 * and every zone the runtime knows to a row. Where a place officially issues
 * one currency and settles in another, the row says which and why. Zones with
 * nobody living in them — Antarctica, `Etc/*`, `UTC` — are left out, as is
 * Europe/Simferopol, where naming a currency would be taking a side; the
 * caller falls back to its own guess for all of them.
 */

